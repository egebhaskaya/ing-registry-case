-- Registry schema, version 1. Flyway runs this once and records it in flyway_schema_history.
-- Design §4 "Registry data".

CREATE TABLE users (
    id                  UUID PRIMARY KEY,          -- generated by the application, no shared counter (design §4)
    registration_id     UUID NOT NULL,             -- the client's Idempotency-Key
    payload_fingerprint VARCHAR(64) NOT NULL,      -- SHA-256 hex of the normalized payload; detects "same key, different data"
    email               VARCHAR(254) NOT NULL,     -- stored normalized (trimmed, lower-case)
    full_name           VARCHAR(100) NOT NULL,
    country_code        CHAR(2) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL,
    -- Both uniqueness rules live in the database, so they also hold when two consumers race (design §5).
    CONSTRAINT users_registration_id_key UNIQUE (registration_id),
    CONSTRAINT users_email_key UNIQUE (email)
);

-- Transactional outbox: one row per UserRegistered event, inserted in the same transaction as the user.
-- Column names are the defaults expected by Debezium's Outbox Event Router, so CDC needs no remapping.
CREATE TABLE outbox (
    id            UUID PRIMARY KEY,                -- stable event id; Compliance deduplicates on it
    aggregatetype VARCHAR(255) NOT NULL,           -- "user"; Debezium routes to the topic outbox.event.user
    aggregateid   VARCHAR(255) NOT NULL,           -- the user id; becomes the Kafka record key
    type          VARCHAR(255) NOT NULL,           -- "UserRegistered"
    payload       JSONB NOT NULL,                  -- the event body as JSON
    created_at    TIMESTAMPTZ NOT NULL
);
